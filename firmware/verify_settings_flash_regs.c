#include "ciu32l071.h"
#include "settings_flash.c"
#define CHECK(a,b) _Static_assert((a)==(b),#a " vendor mismatch")
CHECK(PVD_CR2,PMU_BASE+offsetof(PMU_t,CR2));
CHECK(PVD_SR,PMU_BASE+offsetof(PMU_t,SR));
CHECK(PVD_LOW,PMU_SR_PVD_STATUS);
CHECK(9u,PMU_CR2_PVD_EN|(4u<<PMU_CR2_PVD_LEVEL_POS));
CHECK(NV_IRQ,1u<<UART3_4_IRQn);
CHECK(0x10060000u,RCC_APB1EN_PMUEN|RCC_APB1EN_UART2EN|RCC_APB1EN_UART3EN);
CHECK(0x08000000u,RCC_APB2EN_DBGEN);
CHECK(0x50000828u,GPIOC_BASE+offsetof(GPIO_t,BR));
CHECK(0x50000028u,GPIOA_BASE+offsetof(GPIO_t,BR));
CHECK(0x50000418u,GPIOB_BASE+offsetof(GPIO_t,BSR));
