#include "flash_regs.h"
#include "ciu32l071.h"
#include <stddef.h>
#define CHECK(a,b) _Static_assert((a)==(b), #a " vendor mismatch")
CHECK(FP_ACR,FLASH_REGISTERS_BASE+offsetof(FLASH_t,ACR));
CHECK(FP_KEY,FLASH_REGISTERS_BASE+offsetof(FLASH_t,CRKEY));
CHECK(FP_SR,FLASH_REGISTERS_BASE+offsetof(FLASH_t,SR));
CHECK(FP_CR,FLASH_REGISTERS_BASE+offsetof(FLASH_t,CR));
CHECK(FP_OPTR,FLASH_REGISTERS_BASE+offsetof(FLASH_t,OPTR1));
CHECK(FP_WRPAS,FLASH_REGISTERS_BASE+offsetof(FLASH_t,WRP1AS));
CHECK(FP_WRPAE,FLASH_REGISTERS_BASE+offsetof(FLASH_t,WRP1AE));
CHECK(FP_WRPBS,FLASH_REGISTERS_BASE+offsetof(FLASH_t,WRP1BS));
CHECK(FP_WRPBE,FLASH_REGISTERS_BASE+offsetof(FLASH_t,WRP1BE));
CHECK(FP_BUSY,FLASH_SR_BSY);
CHECK(FP_EOP,FLASH_SR_EOP);
CHECK(FP_ERRORS,FLASH_SR_PROGERR|FLASH_SR_WRPERR|FLASH_SR_FSTERR);
CHECK(FP_LOCK,FLASH_CR_LOCK);
CHECK(FP_OPTLOCK,FLASH_CR_OPTLOCK);
CHECK(FP_PAGE_MODE,FLASH_CR_ER_MODE_PAGE);
CHECK(FP_ERASE,FLASH_CR_ERASE);
CHECK(FP_PROGRAM,FLASH_CR_PG_MODE);
CHECK(0x100u,RCC_AHBEN_FLASHEN);
CHECK(1u,RCC_AHBEN_DMAEN);
CHECK(FP_CSR,RCC_BASE+offsetof(RCC_t,CSR1));
CHECK(FP_READY_MASK,RCC_CSR1_RCHRDY|RCC_CSR1_PLLON|RCC_CSR1_PLLRDY|RCC_CSR1_RCHDIV);
CHECK(FP_READY,RCC_CSR1_RCHRDY|RCC_CSR1_PLLON|RCC_CSR1_PLLRDY);
